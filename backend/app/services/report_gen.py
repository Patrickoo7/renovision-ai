from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer, Image as RLImage
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from app.config import UPLOAD_DIR, OUTPUT_DIR
from pathlib import Path
import uuid

class ReportGenerator:
    def generate_pdf(self, project: dict, materials: dict, estimates: dict) -> str:
        """Generate PDF report, return filename"""
        filename = f"report_{uuid.uuid4().hex[:8]}.pdf"
        filepath = OUTPUT_DIR / filename
        
        doc = SimpleDocTemplate(str(filepath), pagesize=A4,
                              rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
        styles = getSampleStyleSheet()
        title_style = ParagraphStyle('CustomTitle', parent=styles['Title'],
                                      fontSize=20, textColor=colors.HexColor('#1a1a2e'))
        
        elements = []
        
        # Title
        elements.append(Paragraph("Exterior Renovation Estimate", title_style))
        elements.append(Spacer(1, 20))
        elements.append(Paragraph("E2M Solutions — AI-Based Cost Estimation", styles['Heading3']))
        elements.append(Spacer(1, 20))
        
        # Images
        orig_image = project.get('original_image')
        if orig_image:
            orig_path = UPLOAD_DIR / orig_image
            if orig_path.exists():
                elements.append(Paragraph("Original Image", styles['Heading3']))
                elements.append(RLImage(str(orig_path), width=4*inch, height=3*inch))
                elements.append(Spacer(1, 10))
        
        if project.get('redesigned_image'):
            redesigned_path = OUTPUT_DIR / project['redesigned_image']
            if redesigned_path.exists():
                elements.append(Paragraph("Redesigned Image", styles['Heading3']))
                elements.append(RLImage(str(redesigned_path), width=4*inch, height=3*inch))
                elements.append(Spacer(1, 20))
        
        # Cost breakdown table
        if estimates and estimates.get('breakdown'):
            elements.append(Paragraph("Cost Breakdown", styles['Heading2']))
            elements.append(Spacer(1, 10))
            
            table_data = [["Region", "Material", "Area", "Quantity", "Material ₹", "Labor ₹", "Total ₹"]]
            for row in estimates['breakdown']:
                table_data.append([
                    row['segment_label'].title(),
                    row['material_name'],
                    f"{row['area_sqft']} {row['unit']}",
                    f"{row['quantity']} {row['quantity_unit']}",
                    f"₹{row['material_cost']:,.0f}",
                    f"₹{row['labor_cost']:,.0f}",
                    f"₹{row['total_cost']:,.0f}",
                ])
            
            # Totals row
            table_data.append([
                "Total", "", "", "",
                f"₹{estimates.get('total_material_cost', 0):,.0f}",
                f"₹{estimates.get('total_labor_cost', 0):,.0f}",
                f"₹{estimates.get('grand_total', 0):,.0f}",
            ])
            
            table = Table(table_data, repeatRows=1)
            table.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1a1a2e')),
                ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
                ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
                ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                ('FONTSIZE', (0, 0), (-1, -1), 8),
                ('BOTTOMPADDING', (0, 0), (-1, 0), 8),
                ('BACKGROUND', (0, -1), (-1, -1), colors.HexColor('#e8f4f8')),
                ('FONTNAME', (0, -1), (-1, -1), 'Helvetica-Bold'),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
                ('ROWBACKGROUNDS', (0, 1), (-1, -2), [colors.white, colors.HexColor('#f8f8f8')]),
            ]))
            elements.append(table)
            elements.append(Spacer(1, 20))
            
            # Grand total
            elements.append(Paragraph(
                f"<b>Grand Total: ₹{estimates.get('grand_total', 0):,.0f}</b>", 
                ParagraphStyle('GrandTotal', parent=styles['Heading2'], textColor=colors.HexColor('#1a1a2e'))
            ))
        
        elements.append(Spacer(1, 30))
        elements.append(Paragraph(
            "This is an advisory estimate generated by E2M Solutions AI system. "
            "Actual costs may vary based on site conditions, contractor rates, and material availability.",
            styles['Italic']
        ))
        
        doc.build(elements)
        return filename
